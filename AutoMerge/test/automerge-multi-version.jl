using AutoMerge
using GitHub
using Test
using TOML

# Write a minimal registry to `dir`. `packages` maps a package name to a named tuple with
# the fields `uuid`, `versions` (`Vector{VersionNumber}`) and optionally `compat` and `deps`
# (the contents of `Compat.toml` and `Deps.toml`).
function write_test_registry(dir, packages)
    registry_packages = Dict{String,Any}()
    for (name, info) in packages
        path = joinpath(string(first(name)), name)
        registry_packages[info.uuid] = Dict("name" => name, "path" => path)
        mkpath(joinpath(dir, path))
        open(joinpath(dir, path, "Package.toml"), "w") do io
            TOML.print(io, Dict(
                "name" => name,
                "uuid" => info.uuid,
                "repo" => "https://github.com/JuliaBinaryWrappers/$(name).jl.git",
            ))
        end
        open(joinpath(dir, path, "Versions.toml"), "w") do io
            TOML.print(io, Dict(
                string(v) => Dict("git-tree-sha1" => string(hash((name, v)); base=16, pad=40))
                for v in info.versions
            ))
        end
        for (file, field) in (("Compat.toml", :compat), ("Deps.toml", :deps))
            hasproperty(info, field) || continue
            open(io -> TOML.print(io, getproperty(info, field)), joinpath(dir, path, file), "w")
        end
    end
    open(joinpath(dir, "Registry.toml"), "w") do io
        TOML.print(io, Dict(
            "name" => "TestRegistry",
            "uuid" => "8fd42bb9-b78f-4d3a-9a35-4f2a6d0b6f1e",
            "packages" => registry_packages,
        ))
    end
    return dir
end

const FOO_UUID = "3e7c3b6a-5a2c-4d1f-9a43-0a3c3d2f1e01"
const BAR_UUID = "3e7c3b6a-5a2c-4d1f-9a43-0a3c3d2f1e02"
foo(versions; kw...) = (; uuid=FOO_UUID, versions, kw...)
bar(versions; kw...) = (; uuid=BAR_UUID, versions, kw...)

function test_registries(master_packages, head_packages)
    return write_test_registry(mktempdir(), master_packages),
        write_test_registry(mktempdir(), head_packages)
end

const FOO_FILES = ["F/Foo_jll/Versions.toml", "F/Foo_jll/Compat.toml", "F/Foo_jll/Deps.toml"]

@testset "Pull request titles" begin
    pr(t) = GitHub.PullRequest(; title=t)

    # Single-version titles behave as before.
    @test AutoMerge.is_new_version(pr("New version: Foo_jll v1.2.3"))
    @test !AutoMerge.is_new_package(pr("New version: Foo_jll v1.2.3"))
    @test AutoMerge.parse_pull_request_title(AutoMerge.NewVersion(), pr("New version: Foo_jll v1.2.3")) == ("Foo_jll", v"1.2.3")
    @test AutoMerge.parse_pull_request_title_versions(AutoMerge.NewVersion(), pr("New version: Foo_jll v1.2.3+0")) == ("Foo_jll", [v"1.2.3+0"])
    @test AutoMerge.parse_pull_request_title_versions(AutoMerge.NewPackage(), pr("New package: Foo_jll v1.0.0")) == ("Foo_jll", [v"1.0.0"])

    # Several versions.
    t = "New versions: Glibc_jll v2.17.1, v2.19.1, v2.34.1"
    @test AutoMerge.is_new_version(pr(t))
    @test !AutoMerge.is_new_package(pr(t))
    @test AutoMerge.parse_pull_request_title_versions(AutoMerge.NewVersion(), pr(t)) == ("Glibc_jll", [v"2.17.1", v"2.19.1", v"2.34.1"])
    @test_throws ArgumentError AutoMerge.parse_pull_request_title(AutoMerge.NewVersion(), pr(t))
    @test AutoMerge.is_multiple_versions_title(t)
    @test !AutoMerge.is_multiple_versions_title("New version: Glibc_jll v2.34.1")

    t = "New package: Foo_jll v1.0.0, v1.1.0+0"
    @test AutoMerge.is_new_package(pr(t))
    @test !AutoMerge.is_new_version(pr(t))
    @test AutoMerge.parse_pull_request_title_versions(AutoMerge.NewPackage(), pr(t)) == ("Foo_jll", [v"1.0.0", v"1.1.0+0"])

    # Malformed variants are neither.
    for t in ("New versions: Foo_jll v1.0.0",          # "versions" with a single version
              "New version: Foo_jll v1.0.0, v1.1.0",   # "version" with several versions
              "New versions: Foo_jll v1.0.0,v1.1.0",
              "New versions: Foo_jll v1.0.0, 1.1.0")
        @test !AutoMerge.is_new_version(pr(t))
        @test !AutoMerge.is_new_package(pr(t))
    end
end

@testset "Commits for each version" begin
    sha(c) = repeat(c, 40)
    multi_body = """
        Autogenerated JLL package registration

        * Registering JLL package Glibc_jll.jl
        * Repository: https://github.com/JuliaBinaryWrappers/Glibc_jll.jl
        * Version: v2.17.1
        * Commit: $(sha("a"))
        * Version: v2.19.1
        * Commit: $(sha("b"))
        * Version: v2.34.1
        * Commit: $(sha("c"))
        """
    commits = AutoMerge.commits_by_version_from_body(multi_body)
    @test commits == Dict(v"2.17.1" => sha("a"), v"2.19.1" => sha("b"), v"2.34.1" => sha("c"))

    multi_pr = GitHub.PullRequest(; title="New versions: Glibc_jll v2.17.1, v2.19.1, v2.34.1", body=multi_body)
    @test AutoMerge.commit_from_pull_request_body(multi_pr, v"2.19.1") == sha("b")
    @test AutoMerge.commit_from_pull_request_body(multi_pr, v"2.34.1") == sha("c")
    @test_throws ErrorException AutoMerge.commit_from_pull_request_body(multi_pr, v"2.20.0")

    # Single-version pull requests keep using the first `Commit:` line.
    single_pr = GitHub.PullRequest(; title="New version: Foo v1.0.0", body="- Commit: $(sha("d"))\n- Version: v1.0.0\n")
    @test AutoMerge.commit_from_pull_request_body(single_pr, v"1.0.0") == sha("d")

    @test_throws ErrorException AutoMerge.commits_by_version_from_body(
        "Version: v1.0.0\nCommit: $(sha("a"))\nVersion: v1.0.0\nCommit: $(sha("b"))\n"
    )
end

@testset "Versions added by a pull request" begin
    master, head = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0", v"1.1.0"])),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.1.0", v"1.1.1", v"1.2.0"])),
    )
    @test AutoMerge.versions_added_by_pr("Foo_jll"; registry_master=master, registry_head=head) == [v"1.1.1", v"1.2.0"]
    @test AutoMerge.versions_preceding_in_pr("Foo_jll", v"1.1.1"; registry_master=master, registry_head=head) == [v"1.0.0", v"1.1.0"]
    @test AutoMerge.versions_preceding_in_pr("Foo_jll", v"1.2.0"; registry_master=master, registry_head=head) == [v"1.0.0", v"1.1.0", v"1.1.1"]

    # A new package
    master, head = test_registries(
        Dict("Bar_jll" => bar([v"1.0.0"])),
        Dict("Bar_jll" => bar([v"1.0.0"]), "Foo_jll" => foo([v"1.0.0", v"1.1.0"])),
    )
    @test AutoMerge.versions_added_by_pr("Foo_jll"; registry_master=master, registry_head=head) == [v"1.0.0", v"1.1.0"]
    @test AutoMerge.versions_preceding_in_pr("Foo_jll", v"1.0.0"; registry_master=master, registry_head=head) == VersionNumber[]
    @test AutoMerge.versions_preceding_in_pr("Foo_jll", v"1.1.0"; registry_master=master, registry_head=head) == [v"1.0.0"]
end

@testset "Sequential version numbers within one pull request" begin
    seq(v, master, head) = AutoMerge.meets_sequential_version_number("Foo_jll", v; registry_master=master, registry_head=head)[1]

    # Each version follows on from the one before it, including ones added by this PR.
    master, head = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"])),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1", v"1.0.2", v"1.1.0"])),
    )
    @test seq(v"1.0.1", master, head)
    @test seq(v"1.0.2", master, head)
    @test seq(v"1.1.0", master, head)

    # One bad version among good ones.
    master, head = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"])),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1", v"1.0.3"])),
    )
    @test seq(v"1.0.1", master, head)
    @test !seq(v"1.0.3", master, head)

    # A single new version behaves as before.
    master, head = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"])),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.2"])),
    )
    @test !seq(v"1.0.2", master, head)

    # A new package: the lowest version is unconstrained here, later ones must follow on.
    master, head = test_registries(
        Dict("Bar_jll" => bar([v"1.0.0"])),
        Dict("Bar_jll" => bar([v"1.0.0"]), "Foo_jll" => foo([v"1.0.0", v"1.1.0", v"1.3.0"])),
    )
    @test seq(v"1.0.0", master, head)
    @test seq(v"1.1.0", master, head)
    @test !seq(v"1.3.0", master, head)
end

@testset "Patch releases within one pull request cannot narrow Julia compat" begin
    narrow(v, master, head) = AutoMerge.meets_patch_release_does_not_narrow_julia_compat("Foo_jll", v; registry_master=master, registry_head=head)[1]
    master_pkgs = Dict("Foo_jll" => foo([v"1.0.0"]; compat=Dict("1" => Dict("julia" => "1.6.0-1"))))
    # v1.0.2 narrows the range relative to v1.0.1, which the same PR adds.
    head_pkgs = Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1", v"1.0.2"];
        compat=Dict("1.0.0-1.0.1" => Dict("julia" => "1.6.0-1"), "1.0.2-1" => Dict("julia" => "1.10.0-1"))))
    master, head = test_registries(master_pkgs, head_pkgs)
    @test narrow(v"1.0.1", master, head)
    @test !narrow(v"1.0.2", master, head)
end

@testset "Registry changes must match the title" begin
    check(files, title_versions, master, head; pkg="Foo_jll") =
        AutoMerge.meets_registry_changes_match_title(files, pkg, title_versions; registry_master=master, registry_head=head)

    compat = Dict("1" => Dict("julia" => "1.6.0-1"))
    deps = Dict("1" => Dict("Libdl" => "8f399da3-3557-5675-b5ff-fb832c97cbdb"))
    master, head = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"]; compat, deps), "Bar_jll" => bar([v"1.0.0"])),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1", v"1.1.0"]; compat, deps), "Bar_jll" => bar([v"1.0.0"])),
    )
    @test check(FOO_FILES, [v"1.0.1", v"1.1.0"], master, head) == (true, "")
    # A title that leaves out a version, lists one that isn't added, or is out of order.
    ok, msg = check(FOO_FILES, [v"1.1.0"], master, head)
    @test !ok
    @test occursin("v1.0.1, v1.1.0", msg)
    @test !check(FOO_FILES, [v"1.0.1", v"1.1.0", v"1.2.0"], master, head)[1]
    @test !check(FOO_FILES, [v"1.1.0", v"1.0.1"], master, head)[1]

    # A single version.
    master1, head1 = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"])),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1"])),
    )
    @test check(["F/Foo_jll/Versions.toml"], [v"1.0.1"], master1, head1) == (true, "")
    @test !check(["F/Foo_jll/Versions.toml"], [v"1.0.2"], master1, head1)[1]

    # Versions of another package.
    master2, head2 = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"]), "Bar_jll" => bar([v"1.0.0"])),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1"]), "Bar_jll" => bar([v"1.0.0", v"1.0.1"])),
    )
    ok, msg = check(["F/Foo_jll/Versions.toml", "B/Bar_jll/Versions.toml"], [v"1.0.1"], master2, head2)
    @test !ok
    @test occursin("Bar_jll", msg)

    # Changing an existing version's tree hash.
    master3 = write_test_registry(mktempdir(), Dict("Foo_jll" => foo([v"1.0.0"])))
    head3 = write_test_registry(mktempdir(), Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1"])))
    versions_toml = joinpath(head3, "F", "Foo_jll", "Versions.toml")
    versions = TOML.parsefile(versions_toml)
    versions["1.0.0"]["git-tree-sha1"] = repeat("0", 40)
    open(io -> TOML.print(io, versions), versions_toml, "w")
    ok, msg = check(["F/Foo_jll/Versions.toml"], [v"1.0.1"], master3, head3)
    @test !ok
    @test occursin("existing version v1.0.0", msg)

    # Changing the compat or deps of an existing version.
    master4, head4 = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"]; compat, deps)),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1"]; compat=Dict("1" => Dict("julia" => "1.10.0-1")), deps)),
    )
    ok, msg = check(FOO_FILES, [v"1.0.1"], master4, head4)
    @test !ok
    @test occursin("Compat.toml", msg)
    master5, head5 = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"]; compat, deps)),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1"]; compat, deps=Dict("1" => Dict("Evil" => "8f399da3-3557-5675-b5ff-fb832c97cbdc")))),
    )
    ok, msg = check(FOO_FILES, [v"1.0.1"], master5, head5)
    @test !ok
    @test occursin("Deps.toml", msg)
    # Recompressing the ranges without changing what existing versions get is fine.
    master6, head6 = test_registries(
        Dict("Foo_jll" => foo([v"1.0.0"]; compat=Dict("1" => Dict("julia" => "1.6.0-1")))),
        Dict("Foo_jll" => foo([v"1.0.0", v"1.0.1"];
            compat=Dict("1.0.0" => Dict("julia" => "1.6.0-1"), "1.0.1-1" => Dict("julia" => "1.10.0-1")))),
    )
    @test check(["F/Foo_jll/Versions.toml", "F/Foo_jll/Compat.toml"], [v"1.0.1"], master6, head6) == (true, "")

    # New packages: only the package named in the title may be added to `Registry.toml`.
    master7, head7 = test_registries(
        Dict("Bar_jll" => bar([v"1.0.0"])),
        Dict("Bar_jll" => bar([v"1.0.0"]), "Foo_jll" => foo([v"1.0.0", v"1.1.0"])),
    )
    files7 = ["Registry.toml", "F/Foo_jll/Package.toml", "F/Foo_jll/Versions.toml"]
    @test check(files7, [v"1.0.0", v"1.1.0"], master7, head7) == (true, "")
    ok, msg = check(files7, [v"1.0.0", v"1.1.0"], master7, head7; pkg="Baz_jll")
    @test !ok
    @test occursin("adds Foo_jll to `Registry.toml`", msg)
    master8, head8 = test_registries(
        Dict("Bar_jll" => bar([v"1.0.0"])),
        Dict("Foo_jll" => foo([v"1.0.0"])),
    )
    ok, msg = check(["Registry.toml", "F/Foo_jll/Versions.toml"], [v"1.0.0"], master8, head8)
    @test !ok
    @test occursin("removes the existing `Registry.toml` entry of Bar_jll", msg)
end

@testset "Every version is checked" begin
    # Fake guidelines: a PR-level one, a per-version one that fails for v1.0.2 only,
    # and the `:early_exit_if_failed`/`:update_status` markers.
    pr_level = AutoMerge.Guideline(; info="pr level", check=d -> (true, ""))
    per_version = AutoMerge.Guideline(; info="per version",
        check=d -> d.version == v"1.0.2" ? (false, "bad version") : (true, ""))
    pr_level_calls = Ref(0)
    counted_pr_level = AutoMerge.Guideline(; info="counted", check=d -> (pr_level_calls[] += 1; (true, "")))
    guidelines_for(d, i) = [(pr_level, true), (counted_pr_level, true), (:update_status, true), (per_version, true)]
    once = [pr_level, counted_pr_level]

    all_data = [(; version=v) for v in (v"1.0.1", v"1.0.2", v"1.0.3")]
    failures_reported = Ref(0)
    checked = AutoMerge.run_guidelines(all_data, guidelines_for; once, on_failure_so_far=() -> failures_reported[] += 1)
    @test pr_level_calls[] == 1
    @test [v for (v, g) in checked if g.info == "per version"] == [v"1.0.1", v"1.0.2", v"1.0.3"]
    @test [v for (v, g) in checked if !AutoMerge.passed(g)] == [v"1.0.2"]
    # The marker runs before `per_version`, so only v1.0.3's sees the v1.0.2 failure.
    @test failures_reported[] == 1
    @test AutoMerge.failing_guideline_messages(checked; multiple_versions=true) == ["`v1.0.2`: bad version"]

    # All good.
    all_good = [(; version=v) for v in (v"1.0.1", v"1.0.3")]
    checked = AutoMerge.run_guidelines(all_good, guidelines_for; once)
    @test all(AutoMerge.passed(g) for (_, g) in checked)

    # Single version: messages are not prefixed.
    checked = AutoMerge.run_guidelines([(; version=v"1.0.2")], guidelines_for; once)
    @test AutoMerge.failing_guideline_messages(checked; multiple_versions=false) == ["bad version"]

    # `:early_exit_if_failed` stops checking the remaining versions too.
    early = AutoMerge.Guideline(; info="early", check=d -> (false, "bad name"))
    calls = Ref(0)
    after = AutoMerge.Guideline(; info="after", check=d -> (calls[] += 1; (true, "")))
    checked = AutoMerge.run_guidelines(all_data, (d, i) -> [(early, true), (:early_exit_if_failed, true), (after, true)]; once=[early])
    @test calls[] == 0
    @test AutoMerge.failing_guideline_messages(checked; multiple_versions=true) == ["bad name"]

    # Guideline constants are not mutated.
    @test startswith(per_version.message, "Internal error")
end

@testset "Guideline lists" begin
    kw = (; check_license=false, check_breaking_explanation=false, this_is_jll_package=true,
        allow_build_metadata=false, use_distance_check=false, package_author_approved=false)
    has(gs, g) = any(x -> x[1] === g && x[2], gs)
    for type in (AutoMerge.NewPackage(), AutoMerge.NewVersion())
        @test has(AutoMerge.get_automerge_guidelines(type; this_pr_can_use_special_jll_exceptions=true, kw...),
            AutoMerge.guideline_registry_changes_match_title)
    end
    seq = AutoMerge.guideline_sequential_version_number
    @test !has(AutoMerge.get_automerge_guidelines(AutoMerge.NewPackage(); this_pr_can_use_special_jll_exceptions=false, kw...), seq)
    @test has(AutoMerge.get_automerge_guidelines(AutoMerge.NewPackage(); this_pr_can_use_special_jll_exceptions=false, later_version_in_pr=true, kw...), seq)
    @test !has(AutoMerge.get_automerge_guidelines(AutoMerge.NewPackage(); this_pr_can_use_special_jll_exceptions=true, later_version_in_pr=true, kw...), seq)
end
